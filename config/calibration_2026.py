def blended_defence(starter_factor: float, ip_per_start: float,
                    bullpen_factor: float) -> float:
    """把先發與牛棚依預期局數混成當日守備係數。"""
    w = min(max(ip_per_start / 9.0, 0.35), 0.75)
    return w * starter_factor + (1.0 - w) * bullpen_factor


